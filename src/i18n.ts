export function getSavedLanguage(): AppLanguage {
  const saved = typeof localStorage !== 'undefined' ? localStorage.getItem(STORAGE_KEY) : '';
  if (isAppLanguage(saved)) return saved;
  const preferred = typeof navigator !== 'undefined'
    ? [navigator.language, ...(navigator.languages || [])]
    : [];
  for (const value of preferred) {
    const normalized = normalizeLanguage(value);
    if (normalized) return normalized;
  }
  return 'pt-BR';
}

export function saveLanguage(language: AppLanguage) {
  localStorage.setItem(STORAGE_KEY, language);
}

export function normalizeLanguage(value: unknown): AppLanguage | null {
  const raw = String(value || '').trim().toLowerCase();
  if (!raw) return null;
  if (raw === 'pt' || raw === 'pt-br') return 'pt-BR';
  if (raw === 'zh' || raw === 'zh-cn' || raw === 'zh-hans') return 'zh-CN';
  const base = raw.split('-')[0];
  if (base === 'en') return 'en';
  if (base === 'es') return 'es';
  if (base === 'fr') return 'fr';
  if (base === 'it') return 'it';
  if (base === 'ja') return 'ja';
  if (base === 'ru') return 'ru';
  return null;
}

export function isAppLanguage(value: unknown): value is AppLanguage {
  return LANGUAGE_OPTIONS.some((option) => option.code === value);
}

export function t(language: AppLanguage, key: TranslationKey, vars?: Record<string, string | number>) {
  let text = translations[language]?.[key] || translations['pt-BR'][key] || key;
  if (vars) {
    Object.entries(vars).forEach(([name, value]) => {
      text = text.replaceAll(`{${name}}`, String(value));
    });
  }
  return text;
}
